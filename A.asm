ReadNumber proc near USES bx cx dx si

    mov currentBase, cl
    mov inputCharCount, 0
    xor bx, bx

ReadDigitLoop:
    mov ah, 00h
    int 16h

    cmp al, 0Dh         ; Enter?
    jne NotEnterKey
    jmp FinishReadNumber
NotEnterKey:

    cmp al, 08h         ; Backspace?
    je HandleBackspaceNumber

    push ax

    cmp al, 'a'
    jl CheckAgainstValidChars
    cmp al, 'f'
    jle CheckLowerF
    jmp InvalidChar_CleanupAx
CheckLowerF:
    sub al, 20h

CheckAgainstValidChars:
    mov ah, al
    lea si, VALID_CHARS
    mov cl, currentBase
    mov ch, 0
    xor dx, dx

ValidateLoop:
    cmp byte ptr [si], ah
    je FoundValidChar
    inc si
    inc dl
    loop ValidateLoop

    jmp InvalidChar_CleanupAx

FoundValidChar:
    push dx             
    mov ax, bx          
    mov cl, currentBase 
    mov ch, 0
    mul cx              
    cmp dx, 0           
    pop dx              
    jne OverflowIgnoreDigit

    push ax             
    mov dh, 0
    add ax, dx          
    jnc CanAddDigit     
    pop ax              
    jmp OverflowIgnoreDigit

CanAddDigit:
    mov bx, ax          
    pop ax              
    pop ax              
    PrintBIOSChar       
    inc inputCharCount  
    jmp ReadDigitLoop

HandleBackspaceNumber:
    cmp inputCharCount, 0 
    jne ProcessBackspace  
    jmp ReadDigitLoop     

ProcessBackspace:
    dec inputCharCount    
    mov al, 08h
    PrintBIOSChar
    mov al, SPACE_CHAR
    PrintBIOSChar
    mov al, 08h
    PrintBIOSChar

    cmp bx, 0           
    jne PerformDivision
    jmp ReadDigitLoop

PerformDivision:
